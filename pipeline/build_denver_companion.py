"""Assemble Denver's ordered browser scripts into one versioned Oracle asset."""
import argparse
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[1] / 'app' / 'assets' / 'denver'
SOURCES = ('denver-sprite.js', 'denver-motions.js', 'denver-widget.js', 'denver-oracle.js')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bundle = ASSETS / 'oracle-companion.js'
    code = '// Generated by pipeline/build_denver_companion.py from the Denver kit.\n'
    code += '\n;\n'.join((ASSETS / name).read_text().rstrip() for name in SOURCES) + '\n'
    if args.check:
        if bundle.read_text() != code:
            raise SystemExit('Run python3 pipeline/build_denver_companion.py and update the asset version.')
    else:
        bundle.write_text(code)


if __name__ == '__main__':
    main()
